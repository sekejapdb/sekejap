/// The midpoints of a ring's four constant-coordinate edges, all four ways,
/// against this PostGIS 3.6 server. The ring is family B's `on_outer_boundary`
/// outer ring; the probes are `ST_Intersects`/`ST_Distance` of each midpoint
/// against it as a geography.
///
/// ```text
/// north-edge midpoint   true, 0          (2.73 cm INSIDE: the geodesic bulges out)
/// south-edge midpoint   false, 0.0272812 (2.73 cm OUTSIDE: the geodesic bulges in)
/// west-edge midpoint    true, 0          (a meridian IS its own geodesic)
/// ring vertex           true, 0
/// ```
///
/// One rule produces all four: a point exactly on a straight chord is inside
/// the geography ring iff it is on the ring's interior side of that edge's
/// own great circle. North and south are opposite signs of the same
/// centimetre, which is why a fix that only knew about "north edges" would
/// have been wrong half the time — and why
/// `tests/spatial_geometry_postgis.rs` (a south edge, PostGIS 3.4, 1.2 cm)
/// and this file (a north edge, PostGIS 3.6, 2.7 cm) now agree.
#[test]
fn documented_constant_latitude_edge_midpoints() {
    let ring = r#"{"type":"Polygon","coordinates":[[[37.57643279187031,55.83328687951804],[37.59197956580869,55.83328687951804],[37.59197956580869,55.84201701091608],[37.57643279187031,55.84201701091608],[37.57643279187031,55.83328687951804]]]}"#;
    let r = gj(ring);
    let pt = |lon: f64, lat: f64| Geom::Point(lon, lat);

    let north_mid = pt(37.5842061788395, 55.84201701091608);
    assert!(intersects(&north_mid, &r), "north-edge midpoint is inside (postgis true)");
    assert!(dist_ok(distance_m(&north_mid, &r), 0.0), "postgis 0");

    let south_mid = pt(37.5842061788395, 55.83328687951804);
    assert!(!intersects(&south_mid, &r), "south-edge midpoint is outside (postgis false)");
    assert!(
        dist_ok(distance_m(&south_mid, &r), 0.02728116),
        "e4 distance_m={} postgis=0.02728116",
        distance_m(&south_mid, &r)
    );

    let west_mid = pt(37.57643279187031, 55.83765194521706);
    assert!(intersects(&west_mid, &r), "a meridian edge has no bulge (postgis true)");
    assert!(dist_ok(distance_m(&west_mid, &r), 0.0), "postgis 0");

    let vertex = pt(37.57643279187031, 55.83328687951804);
    assert!(intersects(&vertex, &r), "a ring vertex is on the boundary (postgis true)");
    assert!(dist_ok(distance_m(&vertex, &r), 0.0), "postgis 0");
}

/// A `geography` edge is the GREAT CIRCLE through its two vertices — with
/// `(lon, lat)` read straight onto a sphere — and NOT the WGS84 geodesic.
/// Only the distances between points are spheroidal. This is the fact
/// `point_to_segment_geodesic_m` is built on, and it is worth an assertion
/// because the two models part by kilometres once an edge is wide.
///
/// Family G's 117.48°-wide south edge at latitude 29.503844920576796, probed
/// on this server:
///
/// ```sql
/// SELECT ST_AsText(ST_ClosestPoint(edge::geography, corner::geography));
/// -- POINT(80.86411847825508 47.475329257577954)
/// SELECT ST_Distance(edge::geography, corner::geography);
/// -- 25246.58142148
/// ```
///
/// `atan(tan(29.503844920576796°) / cos(117.48°/2))` = 47.475329°, the great
/// circle's own maximum latitude, to eight figures. The WGS84 geodesic
/// between the same two vertices tops out at 47.566990° instead — 10.2 km
/// further north — and interpolating along IT moves this answer to
/// 35,223.56 m, a 39% error against the server.
#[test]
fn documented_postgis_edges_are_great_circles() {
    let edge = gj(r#"{"type":"LineString","coordinates":[[22.78819591825288,29.503844920576796],[140.2671822376068,29.503844920576796]]}"#);
    let corner = Geom::Point(80.86697379197149, 47.248254802787805);
    let got = distance_m(&edge, &corner);
    assert!(
        dist_ok(got, 25_246.581_421_48),
        "e4 distance_m={got} postgis=25246.58142148 (great-circle edge); \
         the WGS84-geodesic edge would give 35223.56"
    );
    // And the closest point PostGIS names is ON that great circle, to
    // fourteen decimal places of a degree. For a great circle with maximum
    // latitude `φm` at longitude `λm`, `tan φ(λ) = tan φm · cos(λ − λm)`,
    // with `tan φm = tan φ / cos(Δλ/2)` from the two same-latitude vertices.
    let (lat, lon_a, lon_b) = (
        29.503_844_920_576_796f64,
        22.788_195_918_252_88f64,
        140.267_182_237_606_8f64,
    );
    let (span, lon_mid) = (lon_b - lon_a, (lon_a + lon_b) / 2.0);
    let tan_max = lat.to_radians().tan() / (span / 2.0).to_radians().cos();
    let closest_lon = 80.864_118_478_255_08f64;
    let on_circle = (tan_max * (closest_lon - lon_mid).to_radians().cos())
        .atan()
        .to_degrees();
    assert!(
        (on_circle - 47.475_329_257_577_954).abs() < 1e-9,
        "great circle at lon {closest_lon}: {on_circle}; ST_ClosestPoint 47.475329257577954"
    );
}

