/// Family D unclosed ring: E4 `ring_edges` adds the closing edge; PostGIS
/// `ST_IsValid` is false ("Points of LinearRing do not form a closed
/// linestring") and `ST_Area`/`ST_Perimeter` measure the open ring (area
/// ~half, perimeter 3 sides of 4).
///
/// DOCUMENTED, not copied: rings are implicitly closed by spec
/// (`core/kernel/src/spatial.rs:348`). This test asserts E4's normalisation —
/// exactly twice PostGIS's area, and the fourth side's length on top of
/// PostGIS's perimeter — so the choice stays visible and a drift in either
/// direction fails.
#[test]
fn documented_unclosed_ring_e4_closes_postgis_does_not() {
    let a = gj(r#"{"type":"Polygon","coordinates":[[[-73.6610518305111,40.47008944877067],[-73.65914914875398,40.47008944877067],[-73.65914914875398,40.47153688861146],[-73.6610518305111,40.47153688861146]]]}"#);
    // The same ring written closed: E4's normalisation is exactly this, and
    // stating it that way is stronger than a magic constant.
    let closed = gj(r#"{"type":"Polygon","coordinates":[[[-73.6610518305111,40.47008944877067],[-73.65914914875398,40.47008944877067],[-73.65914914875398,40.47153688861146],[-73.6610518305111,40.47153688861146],[-73.6610518305111,40.47008944877067]]]}"#);
    let (got_area, got_perim) = (area_m2(&a), perimeter_m(&a));
    assert!(
        area_ok(got_area, area_m2(&closed)) && dist_ok(got_perim, perimeter_m(&closed)),
        "e4 measures the unclosed ring as the closed one: area_m2={got_area} perimeter_m={got_perim}"
    );
    // PostGIS refuses validity and measures something else: half the area
    // (`ST_IsValid` false, "Points of LinearRing do not form a closed
    // linestring") and three of the four sides.
    let pg_area = 12_967.435_211_658_478;
    let pg_perim = 483.440_976_631_772_86;
    assert!(
        !area_ok(got_area, pg_area) && !dist_ok(got_perim, pg_perim),
        "the documented disagreement: e4 ({got_area} m², {got_perim} m) vs postgis ({pg_area} m², {pg_perim} m)"
    );
}

