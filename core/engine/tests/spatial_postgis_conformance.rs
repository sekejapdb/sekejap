fn family_d_degenerate_inputs() {
    let mut rows = Vec::new();
    for pair in load_pairs("d_degenerate") {
        let i = pair["i"].as_u64().unwrap() as usize;
        let tag = pair["tag"].as_str().unwrap_or("").to_string();
        let ajs = js(&pair["a"]);
        let bjs = js(&pair["b"]);
        let pg = &pair["postgis"];
        let parsed = pair_geoms(&pair);
        // E4's Geom constructor does not refuse: rings are implicitly closed
        // (`core/kernel/src/spatial.rs:348`, `ring_edges` in spatial_geometry.rs).
        let (a, b) = match parsed {
            Ok(v) => v,
            Err(e) => {
                rows.push(Disagree {
                    family: "d",
                    i,
                    tag: tag.clone(),
                    pred: "e4_parse".into(),
                    a: ajs,
                    b: bjs,
                    postgis: format!("a_valid={}", pg["a_valid"]),
                    e4: format!("refuse: {e}"),
                });
                continue;
            }
        };
        let e4_behaviour = if tag == "unclosed_ring" {
            "normalise_implicit_close"
        } else {
            "accept"
        };
        eprintln!(
            "d[{i}] tag={tag} postgis_valid={} reason={} e4={e4_behaviour}",
            pg["a_valid"],
            pg["a_valid_reason"].as_str().unwrap_or(""),
        );
        let mut push = |pred: &str, e4: String, postgis: String, ok: bool| {
            if ok {
                return;
            }
            if let Some(why) = documented_deviation("d", &tag, pred, &a, &b, pg) {
                eprintln!("DOCUMENTED d[{i}] tag={tag} pred={pred} e4={e4} postgis={postgis}: {why}");
                return;
            }
            rows.push(Disagree {
                family: "d",
                i,
                tag: tag.clone(),
                pred: pred.to_string(),
                a: ajs.clone(),
                b: bjs.clone(),
                postgis,
                e4,
            });
        };
        if let Some(want) = f64_field(pg, "a_area_m2") {
            let got = area_m2(&a);
            push("area_m2", format!("{got}"), format!("{want}"), area_ok(got, want));
        }
        if let Some(want) = f64_field(pg, "a_perimeter_m") {
            let got = perimeter_m(&a);
            push(
                "perimeter_m",
                format!("{got}"),
                format!("{want}"),
                dist_ok(got, want),
            );
        }
        if let (Some(wlon), Some(wlat)) = (f64_field(pg, "a_centroid_lon"), f64_field(pg, "a_centroid_lat"))
        {
            match centroid(&a) {
                None => push(
                    "centroid",
                    "None".into(),
                    format!("[{wlon},{wlat}]"),
                    false,
                ),
                Some(got) => {
                    let gap = lonlat_gap_deg(got, (wlon, wlat));
                    push(
                        "centroid",
                        format!("[{},{}] gap_deg={gap}", got.0, got.1),
                        format!("[{wlon},{wlat}]"),
                        gap <= centroid_tol(&a),
                    );
                }
            }
        }
        if let Some(want) = bool_field(pg, "intersects") {
            let got = intersects(&a, &b);
            push("intersects", got.to_string(), want.to_string(), got == want);
        }
        if let Some(want) = bool_field(pg, "point_within_a") {
            let got = within(&b, &a);
            push("within(point,a)", got.to_string(), want.to_string(), got == want);
        }
        if let Some(want) = bool_field(pg, "a_contains_point") {
            let got = contains(&a, &b);
            push("contains", got.to_string(), want.to_string(), got == want);
        }
        if let Some(want) = f64_field(pg, "distance_m") {
            let got = distance_m(&a, &b);
            push(
                "distance_m",
                format!("{got}"),
                format!("{want}"),
                dist_ok(got, want),
            );
        }
    }
    finish("d_degenerate", &rows);
}

